#!/usr/bin/env python3
"""Build the server-side compile overlay for the engine spike (run from repo root).

1. tool/engine_spike/.build/overlay/lib: a symlink farm of lib/ in which ONLY
   these files are replaced by spike shims (everything else is the unchanged
   app source):
     lib/data/database/{interaction,user,core}_database.dart  (Drift + dart:io + FFI)
     lib/services/crash_reporting_service.dart              (sentry_flutter)
2. tool/engine_spike/.build/package_config.json: the app's resolved packages,
   with `pharmaguide` -> overlay, `flutter` -> shims/flutter (foundation/material
   only) and `engine_spike` -> tool/engine_spike.
3. tool/engine_spike/lib/src/fixture_data.g.dart: fixtures embedded as string
   constants, so the same entry runs under the VM, AOT and dart2js (Deno) with
   no file I/O.
"""
import json
import os
import shutil

ROOT = os.getcwd()
SPIKE = os.path.join(ROOT, 'tool', 'engine_spike')
BUILD = os.path.join(SPIKE, '.build')
OVERLAY_LIB = os.path.join(BUILD, 'overlay', 'lib')
SHIMS = os.path.join(SPIKE, 'shims', 'overlay')

REPLACED = {
    'data/database/interaction_database.dart',
    'data/database/user_database.dart',
    'data/database/core_database.dart',
    'services/crash_reporting_service.dart',
}
# Directories that must be real (not symlinked) because they contain a replaced file.
REAL_DIRS = {'', 'data', 'data/database', 'services'}


def farm(rel=''):
    src = os.path.join(ROOT, 'lib', rel)
    dst = os.path.join(OVERLAY_LIB, rel)
    os.makedirs(dst, exist_ok=True)
    for name in sorted(os.listdir(src)):
        child = os.path.join(rel, name) if rel else name
        if child in REPLACED:
            shutil.copyfile(os.path.join(SHIMS, child), os.path.join(dst, name))
        elif child in REAL_DIRS:
            farm(child)
        else:
            os.symlink(os.path.join(src, name), os.path.join(dst, name))


def package_config():
    with open(os.path.join(ROOT, '.dart_tool', 'package_config.json')) as f:
        app = json.load(f)
    out = []
    for p in app['packages']:
        if p['name'] in ('pharmaguide', 'flutter'):
            continue
        root_uri = p['rootUri']
        if not root_uri.startswith('file:'):
            # relative to <repo>/.dart_tool/ in the app config -> make absolute
            root_uri = 'file://' + os.path.normpath(os.path.join(ROOT, '.dart_tool', root_uri))
        out.append({**p, 'rootUri': root_uri})
    app_lang = next(p for p in app['packages'] if p['name'] == 'pharmaguide')['languageVersion']
    out += [
        {'name': 'pharmaguide', 'rootUri': 'file://' + os.path.dirname(OVERLAY_LIB),
         'packageUri': 'lib/', 'languageVersion': app_lang},
        {'name': 'flutter', 'rootUri': 'file://' + os.path.join(SPIKE, 'shims', 'flutter'),
         'packageUri': 'lib/', 'languageVersion': app_lang},
        {'name': 'engine_spike', 'rootUri': 'file://' + SPIKE,
         'packageUri': 'lib/', 'languageVersion': app_lang},
    ]
    with open(os.path.join(BUILD, 'package_config.json'), 'w') as f:
        json.dump({'configVersion': 2, 'packages': out}, f, indent=1)


def embed_fixtures():
    fx = os.path.join(SPIKE, 'fixtures')
    consts = {
        'kStackJson': 'stack.json',
        'kInteractionsJson': 'interactions.json',
        'kInteractionsAllLiveJson': 'interactions_all_live.json',
        'kDrugClassMapJson': 'drug_class_map.json',
        'kProductsJson': 'products.json',
        'kDepletionsJson': '../../../assets/reference_data/medication_depletions.json',
    }
    lines = ['// GENERATED by tool/engine_spike/make_overlay.py. Do not edit.', '']
    for const, fname in consts.items():
        with open(os.path.join(fx, fname)) as f:
            text = f.read()
        assert "'''" not in text, fname
        lines.append(f"const String {const} = r'''{text}''';")
        lines.append('')
    os.makedirs(os.path.join(SPIKE, 'lib', 'src'), exist_ok=True)
    with open(os.path.join(SPIKE, 'lib', 'src', 'fixture_data.g.dart'), 'w') as f:
        f.write('\n'.join(lines))


if __name__ == '__main__':
    shutil.rmtree(BUILD, ignore_errors=True)
    os.makedirs(BUILD)
    farm()
    package_config()
    embed_fixtures()
    print('overlay ready:', BUILD)
